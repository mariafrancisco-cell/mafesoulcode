package ListaDeRevisãoComRef;

public class variaveisEtipo {
    static void main(String[] args) {
        String nome = "Mafe";
        int idade = 18;
        double altura = 1.64;
        boolean programou = false;
        System.out.println(nome);
        System.out.println(idade);
        System.out.println(altura);
        System.out.println(programou);

        String cidade = "SP";
        System.out.println("Eu moro em " + cidade);

        String primeiroNome = "Maria Fernanda";
        String sobrenome = "Francisco";
        System.out.println(primeiroNome + " " + sobrenome);

        double preco = 29.90;
        System.out.println("R$" + preco);
        boolean temCarteira = true;
        System.out.println("Tem carteira? " + temCarteira);

        int a = 10;
        int b = 20;
        a = a + b;
        b = a - b;
        a = a - b;

    }
}
